-- RLS Policies
ALTER TABLE facturacion ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Admins can view all facturacion" ON facturacion;
CREATE POLICY "Admins can view all facturacion" 
ON facturacion FOR SELECT 
USING (auth.role() = 'service_role' OR EXISTS (
  SELECT 1 FROM admins WHERE email = auth.email()
));

DROP POLICY IF EXISTS "Admins can insert facturacion" ON facturacion;
CREATE POLICY "Admins can insert facturacion" 
ON facturacion FOR INSERT 
WITH CHECK (auth.role() = 'service_role' OR EXISTS (
  SELECT 1 FROM admins WHERE email = auth.email()
));

DROP POLICY IF EXISTS "Admins can update facturacion" ON facturacion;
CREATE POLICY "Admins can update facturacion" 
ON facturacion FOR UPDATE 
USING (auth.role() = 'service_role' OR EXISTS (
  SELECT 1 FROM admins WHERE email = auth.email()
));

